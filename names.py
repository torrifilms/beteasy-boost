def _norm(name: str) -> str:
    text = name.casefold().replace("’", "'").replace(".", " ")
    text = text.replace("&", " and ")
    text = text.replace("é", "e").replace("ö", "o").replace("ü", "u").replace("á", "a")
    text = text.replace("ó", "o").replace("í", "i").replace("ñ", "n").replace("ç", "c")
    text = re.sub(r"[^a-zа-я0-9 ]+", " ", text)
    text = re.sub(r"\b(fc|afc|sc|ac|cf|osc|sv|vfb|vfl|rcd|cd|as|ogc|rc|fsv|tsg)\b", " ", text)
    return re.sub(r"\s+", " ", text).strip()


_INDEX = {_norm(english): russian for english, russian in _RAW.items()}
_REPLACEMENTS = sorted(_RAW.items(), key=lambda item: len(item[0]), reverse=True)


def russian_team_name(name: str) -> str:
    found = _INDEX.get(_norm(name))
    return found if found else name.strip()


def russian_names_in_text(text: str) -> str:
    updated = text
    for english, russian in _REPLACEMENTS:
        updated = updated.replace(english, russian)
    return updated
